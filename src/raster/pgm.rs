//! Streaming reader for binary PGM (P5, maxval 255): Ghostscript's `pgmraw` output, one
//! image per PDF page, read page by page so a long document never sits in memory as
//! 8-bit data (an A4 page at 600 dpi is 32 MB).

use crate::error::{CanonError, Result};
use std::io::{BufRead, ErrorKind};

/// Same limit as the PBM reader: anything far beyond A4 at 600 dpi is a corrupt header.
const MAX_DIM: usize = 20_000;

fn bad(msg: impl Into<String>) -> CanonError {
    CanonError::Raster(format!("PGM: {}", msg.into()))
}

fn peek<R: BufRead>(r: &mut R) -> Result<Option<u8>> {
    let buf = r.fill_buf().map_err(|e| bad(format!("read error: {e}")))?;
    Ok(buf.first().copied())
}

fn next<R: BufRead>(r: &mut R) -> Result<Option<u8>> {
    let b = peek(r)?;
    if b.is_some() {
        r.consume(1);
    }
    Ok(b)
}

/// Skip whitespace and `#` comments between header fields.
fn skip_separators<R: BufRead>(r: &mut R) -> Result<()> {
    loop {
        match peek(r)? {
            Some(c) if c.is_ascii_whitespace() => r.consume(1),
            Some(b'#') => {
                while let Some(c) = next(r)? {
                    if c == b'\n' || c == b'\r' {
                        break;
                    }
                }
            }
            _ => return Ok(()),
        }
    }
}

fn number<R: BufRead>(r: &mut R, what: &str) -> Result<usize> {
    skip_separators(r)?;
    let mut n: usize = 0;
    let mut digits = 0;
    while let Some(c) = peek(r)? {
        if !c.is_ascii_digit() {
            break;
        }
        r.consume(1);
        digits += 1;
        n = n
            .checked_mul(10)
            .and_then(|n| n.checked_add((c - b'0') as usize))
            .ok_or_else(|| bad(format!("{what} too large")))?;
    }
    if digits == 0 {
        return Err(bad(format!("expected {what}")));
    }
    Ok(n)
}

/// Read the next image into `gray` (resized to width × height). `Ok(None)` at a clean end
/// of stream (only whitespace left).
pub fn read_page<R: BufRead>(r: &mut R, gray: &mut Vec<u8>) -> Result<Option<(usize, usize)>> {
    match read_header(r)? {
        None => Ok(None),
        Some((width, height)) => {
            read_body(r, width, height, gray)?;
            Ok(Some((width, height)))
        }
    }
}

/// Read the next image header: `Ok(None)` at a clean end of stream. The caller can check
/// the size before [`read_body`] allocates and reads width × height bytes.
pub fn read_header<R: BufRead>(r: &mut R) -> Result<Option<(usize, usize)>> {
    while let Some(c) = peek(r)? {
        if !c.is_ascii_whitespace() {
            break;
        }
        r.consume(1);
    }
    if peek(r)?.is_none() {
        return Ok(None);
    }
    if next(r)? != Some(b'P') || next(r)? != Some(b'5') {
        return Err(bad("not a binary PGM (expected magic 'P5')"));
    }
    let width = number(r, "width")?;
    let height = number(r, "height")?;
    let maxval = number(r, "maxval")?;
    if width == 0 || height == 0 || width > MAX_DIM || height > MAX_DIM {
        return Err(bad(format!("unsupported size {width}x{height}")));
    }
    if maxval != 255 {
        return Err(bad(format!(
            "maxval {maxval}, only 8-bit (255) is supported"
        )));
    }
    match next(r)? {
        Some(c) if c.is_ascii_whitespace() => {}
        _ => return Err(bad("missing whitespace after maxval")),
    }
    Ok(Some((width, height)))
}

/// Read the width × height pixel bytes that follow a header into `gray`.
pub fn read_body<R: BufRead>(
    r: &mut R,
    width: usize,
    height: usize,
    gray: &mut Vec<u8>,
) -> Result<()> {
    gray.resize(width * height, 0);
    r.read_exact(gray).map_err(|e| match e.kind() {
        ErrorKind::UnexpectedEof => bad(format!("truncated {width}x{height} image")),
        _ => bad(format!("read error: {e}")),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    fn page(w: usize, h: usize, fill: u8, comment: bool) -> Vec<u8> {
        let mut v = if comment {
            format!("P5\n# Image generated by GPL Ghostscript (device=pgmraw)\n{w} {h}\n255\n")
                .into_bytes()
        } else {
            format!("P5 {w} {h} 255\n").into_bytes()
        };
        v.extend(vec![fill; w * h]);
        v
    }

    #[test]
    fn reads_pages_in_sequence() {
        let mut data = page(3, 2, 7, true);
        data.extend(page(4, 1, 200, false));
        data.extend(b"\n");
        let mut r = Cursor::new(data);
        let mut g = Vec::new();
        assert_eq!(read_page(&mut r, &mut g).unwrap(), Some((3, 2)));
        assert_eq!(g, vec![7; 6]);
        assert_eq!(read_page(&mut r, &mut g).unwrap(), Some((4, 1)));
        assert_eq!(g, vec![200; 4]);
        assert_eq!(read_page(&mut r, &mut g).unwrap(), None);
        assert_eq!(
            read_page(&mut Cursor::new(Vec::new()), &mut g).unwrap(),
            None
        );
    }

    #[test]
    fn data_may_start_with_whitespace_bytes() {
        // gray value 10 = '\n', 32 = ' ': only ONE separator byte follows maxval
        let mut d = b"P5\n2 1\n255\n".to_vec();
        d.extend([10, 32]);
        let mut g = Vec::new();
        assert_eq!(
            read_page(&mut Cursor::new(d), &mut g).unwrap(),
            Some((2, 1))
        );
        assert_eq!(g, vec![10, 32]);
    }

    #[test]
    fn rejects_malformed_input() {
        let mut g = Vec::new();
        for bad_input in [
            &b"P4\n1 1\n\x00"[..],
            b"P5\n1 1\n65535\n\x00\x00",
            b"P5\n0 1\n255\n",
            b"P5\n99999 1\n255\n",
            b"P5\n2 2\n255\n\x00",
            b"P5\n1 1\n255",
            b"P5\nx 1\n255\n\x00",
            b"P5\n99999999999999999999999 1\n255\n",
        ] {
            assert!(
                read_page(&mut Cursor::new(bad_input), &mut g).is_err(),
                "{bad_input:?}"
            );
        }
    }
}
